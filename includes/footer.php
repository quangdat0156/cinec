        // ==========================================
        // SCROLL REVEAL & COUNT-UP ANIMATION
        // ==========================================
        function initScrollAnimations() {
            // 1. Scroll Reveal Observer
            const revealElements = document.querySelectorAll('.reveal-on-scroll');
            if ('IntersectionObserver' in window) {
                const revealObserver = new IntersectionObserver((entries) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            entry.target.classList.add('is-visible');
                            revealObserver.unobserve(entry.target);
                        }
                    });
                }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

                revealElements.forEach(el => revealObserver.observe(el));
            } else {
                revealElements.forEach(el => el.classList.add('is-visible'));
            }

            // 2. Statistics Count-Up Animation
            const counters = document.querySelectorAll('.stat-counter, [data-counter]');
            if ('IntersectionObserver' in window) {
                const counterObserver = new IntersectionObserver((entries) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            const el = entry.target;
                            const targetText = el.getAttribute('data-target') || el.innerText.trim();
                            const match = targetText.match(/^(\d+)(.*)$/);
                            if (match) {
                                const targetNumber = parseInt(match[1], 10);
                                const suffix = match[2] || '';
                                let start = 0;
                                const duration = 1400;
                                const startTime = performance.now();

                                function updateCount(now) {
                                    const progress = Math.min((now - startTime) / duration, 1);
                                    // Easing cubic-out
                                    const easeOut = 1 - Math.pow(1 - progress, 3);
                                    const currentNumber = Math.floor(easeOut * targetNumber);
                                    el.innerText = currentNumber + suffix;
                                    if (progress < 1) {
                                        requestAnimationFrame(updateCount);
                                    } else {
                                        el.innerText = targetNumber + suffix;
                                    }
                                }
                                requestAnimationFrame(updateCount);
                            }
                            counterObserver.unobserve(el);
                        }
                    });
                }, { threshold: 0.25 });

                counters.forEach(el => counterObserver.observe(el));
            }
        }

        // Khởi chạy animation khi tải trang
        document.addEventListener("DOMContentLoaded", function() {
            initScrollAnimations();
        });
